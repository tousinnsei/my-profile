def escape_attr(value):
    return value.replace('&', '&amp;').replace('"', '&quot;').replace("'", '&#39;')


def make_article(item, idx=None):
    title = item['title']
    label = item['label']
    description = item['description']
    category = item.get('category', 'system')
    attrs = [f'data-category="{escape_attr(category)}"', f'data-category-label="{escape_attr(label)}"', f'data-title="{escape_attr(title)}"', f'data-description="{escape_attr(description)}"']
    if category == 'company':
        attrs += [f'data-research="{escape_attr(item['research'])}"', f'data-role="{escape_attr(item['role'])}"', f'data-results="{escape_attr(item['results'])}"', f'data-stack="{escape_attr(item['stack'])}"', f'data-features="{escape_attr('||'.join(item['features']))}"', f'data-benefits="{escape_attr(item['benefits'])}"', f'data-images="{escape_attr(item['images'])}"', f'data-image="{escape_attr(item['image'])}"']
        body_text = item['card_text']
    elif category == 'system':
        attrs += [f'data-research="{escape_attr(item['overview'])}"', f'data-role=""', f'data-results=""', f'data-stack="{escape_attr(item['stack'])}"', f'data-features="{escape_attr('||'.join(item['features']))}"', f'data-benefits="{escape_attr(item['benefits'])}"', f'data-images="{escape_attr(f'images/system{idx+1}-1.svg,images/system{idx+1}-2.svg,images/system{idx+1}-3.svg')}"', f'data-image="{escape_attr(f'images/system{idx+1}.svg')}"']
        body_text = item['description']
    elif category == 'paper':
        attrs += [f'data-pdf="{escape_attr(item['pdf'])}"', f'data-stack="学術論文"', f'data-image="{escape_attr(item['image'])}"']
        body_text = item['description']
    return f'        <article class="project-card" {' '.join(attrs)}>\n          <div class="project-card__image"><img src="{item['image']}" alt="{title}" loading="lazy" /></div>\n          <div class="project-card__body"><span class="project-card__meta">{label}</span><h3 class="project-card__title">{title}</h3><p class="project-card__text">{body_text}</p></div>\n        </article>'

